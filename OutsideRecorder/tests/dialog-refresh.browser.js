// Run through tools/site/shot.mjs --eval against the Recorder preview.
(async () => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  Mock.state.firstRun = false;
  Mock.state.livestream = {active:false, needsSetup:false};
  Bridge.send('dialogRefreshTest');
  App.open('livestream');
  const modal = document.querySelector('.dialog');
  const select = modal.querySelector('[data-stream-duration]');
  select.value = '8';
  select.dispatchEvent(new Event('change', {bubbles:true}));
  const stableSelect = document.querySelector('[data-stream-duration]');
  stableSelect.focus();
  const stableModal = document.querySelector('.dialog');
  stableModal.scrollTop = 90;
  const scroll = stableModal.scrollTop;
  const rect = stableModal.getBoundingClientRect();
  for (let i=0; i<20; i++) {
    Mock.state.status = {...Mock.state.status, title:`Recording update ${i}`};
    Bridge.send('dialogRefreshTest');
    check(document.querySelector('.dialog') === stableModal, 'Status update replaced the dialog');
    check(document.querySelector('[data-stream-duration]') === stableSelect, 'Status update replaced the select');
    check(document.activeElement === stableSelect, 'Status update lost focus');
    check(stableSelect.value === '8', 'Status update reset expiry');
    check(stableModal.scrollTop === scroll, 'Status update reset scroll');
    check(stableModal.getBoundingClientRect().top === rect.top, 'Status update moved dialog');
  }
  Mock.state.livestream.setupReason = 'Close Civ V first.';
  Bridge.send('dialogRefreshTest');
  check(document.querySelector('[data-start-private-stream]').disabled, 'Safety change failed to update confirmation');
  check(document.querySelector('.dialog').scrollTop === scroll, 'Safety update reset scroll');
  document.querySelector('[data-close]').click();
  check(!document.querySelector('.dialog'), 'Cancel failed');
  App.open('livestream');
  document.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true}));
  check(!document.querySelector('.dialog'), 'Escape failed');
  Mock.state.current = {...Mock.state.current, context:'test-active', ended:false, lobby:null};
  Mock.state.livestream = {active:false, needsSetup:false, setupReason:'This game has an unsent save backlog.', followSetupReason:null};
  Bridge.send('dialogRefreshTest');
  App.open('livestream');
  document.querySelector('[data-start-current-save]').click();
  check(!document.querySelector('[data-start-private-stream]').disabled, 'Future link blocked by current backlog');
  check(document.querySelector('[data-start-private-stream]').textContent === 'Prepare future-game link', 'Future exclusion unclear');
  check(!document.querySelector('[data-stream-scope]'), 'Sharing should only follow the player');
  Mock.state.livestream.currentSaveReason = null;
  Mock.state.livestream.active = true;
  Mock.state.livestream.waitingForGame = true;
  Mock.state.livestream.scope = 'player';
  Bridge.send('dialogRefreshTest');
  App.open('livestream');
  check(document.querySelector('[data-start-current-save]').checked, 'Current-save start should be selected');
  check(!document.querySelector('[data-start-private-stream]').disabled, 'Current-save start blocked by backlog');
  check(!document.querySelector('[data-stream-duration]'), 'Existing invite expiry should not change');
  let command;
  const originalSend=Bridge.send;
  Bridge.send=(cmd,args)=>{command={cmd,args};};
  document.querySelector('[data-start-private-stream]').click();
  check(command.cmd==='startLivestream' && command.args.startCurrentSave===true && command.args.scope==='player', 'Current-save confirmation did not reach backend');
  Bridge.send=originalSend;
  App.open('livestream');
  console.log('PASS: dialog/select identity, focus, expiry, scroll and position survive 20 status updates; safety, Cancel and Escape remain responsive.');
})();
